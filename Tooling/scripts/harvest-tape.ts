import {existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync} from "node:fs";
import {dirname, extname, resolve, relative, sep} from "node:path";
import {fileURLToPath, pathToFileURL} from "node:url";
import {canonicalJson} from "../../Assets/Scripts/Engine/core/CanonicalJson";
import {decodeTapeLine, encodeTapeEntry, TapeEntry} from "../../Assets/Scripts/Engine/ai/Tape";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const defaultRoot = resolve(projectRoot, "Assets/Scripts/Content/Tapes");
const generatedHeader = "// Generated by Roomscript harvest-tape v1. Responses are replay data, never gameplay truth.";

/** Accept raw Lens logs or nested MCP JSON text envelopes. Unrelated logs are never retained. */
export function harvestTapeText(source: string): TapeEntry[] {
  if (source.length > 32 * 1024 * 1024) throw new Error("Tape input exceeds the batch size limit; select a smaller byte range");
  const entries = new Map<string, TapeEntry>();
  const addLines = (text: string): void => {
    for (const line of text.split(/\r?\n/)) {
      if (!line.includes("TAPE|")) continue;
      let entry: TapeEntry | undefined;
      try {entry = decodeTapeLine(line);} catch {throw new Error("Invalid or unsafe tape record; no output was written");}
      if (!entry) continue;
      const id = entry.key + ":" + entry.occurrence; const previous = entries.get(id);
      if (previous && canonicalJson(previous) !== canonicalJson(entry)) throw new Error("Conflicting tape occurrence; select one capture batch with --from-byte");
      entries.set(id, entry);
    }
  };
  const visit = (value: unknown, depth: number): void => {
    if (depth > 24) throw new Error("Tape tool-result envelope is too deeply nested");
    if (typeof value === "string") {
      const trimmed = value.trim();
      if (trimmed.startsWith("{") || trimmed.startsWith("[")) {
        let parsed: unknown;
        try {parsed = JSON.parse(trimmed);} catch {addLines(value); return;}
        visit(parsed, depth + 1);
      } else addLines(value);
    } else if (Array.isArray(value)) for (const child of value) visit(child, depth + 1);
    else if (value && typeof value === "object") for (const child of Object.values(value)) visit(child, depth + 1);
  };
  visit(source, 0);
  return [...entries.values()].sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0) || a.occurrence - b.occurrence);
}

export function renderTapeModule(entries: readonly TapeEntry[], typeImport: string): string {
  if (!entries.length) throw new Error("No tape records found; no output was written");
  // Round-trip the same trusted parser before emitting source, including credential checks.
  const validated = harvestTapeText(entries.map(encodeTapeEntry).join("\n"));
  const data = JSON.stringify(validated, null, 2).replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");
  return generatedHeader + "\nimport type {TapeEntry} from " + JSON.stringify(typeImport) + ";\n\nexport const tapeEntries: TapeEntry[] = " + data + ";\n";
}

/** Restrict generated files to the direct Tapes directory. Different existing files are never overwritten. */
export function writeTapeModule(entries: readonly TapeEntry[], outputPath: string, tapesRoot: string = defaultRoot): {path: string; count: number; written: boolean} {
  const output = resolve(outputPath); const root = resolve(tapesRoot);
  if (dirname(output).toLowerCase() !== root.toLowerCase() || extname(output) !== ".ts"
    || !/^[A-Za-z][A-Za-z0-9_-]*\.ts$/.test(output.slice(dirname(output).length + 1))) throw new Error("Output must be a named .ts file directly inside Content/Tapes");
  // Refuse a junction/symlink escape before creating or writing anything.
  const existingParent = dirname(root);
  if (!existsSync(existingParent)) throw new Error("The Content directory must already exist");
  const actualParent = realpathSync(existingParent);
  if (actualParent.toLowerCase() !== existingParent.toLowerCase()) throw new Error("Refusing a redirected Content directory");
  if (existsSync(root) && realpathSync(root).toLowerCase() !== root.toLowerCase()) throw new Error("Refusing a redirected Tapes directory");
  const typeFile = resolve(projectRoot, "Assets/Scripts/Engine/ai/Tape");
  let typeImport = relative(root, typeFile).split(sep).join("/");
  if (!typeImport.startsWith(".")) typeImport = "./" + typeImport;
  const content = renderTapeModule(entries, typeImport);
  const count = new Set(entries.map(entry => entry.key + ":" + entry.occurrence)).size;
  if (existsSync(output)) {
    if (realpathSync(output).toLowerCase() !== output.toLowerCase()) throw new Error("Refusing a redirected tape file");
    if (readFileSync(output, "utf8") === content) return {path: output, count, written: false};
    throw new Error("Output already exists with different content; choose a new tape filename");
  }
  if (!existsSync(root)) mkdirSync(root);
  writeFileSync(output, content, {encoding: "utf8", flag: "wx"});
  return {path: output, count, written: true};
}

export function readTapeFile(inputPath: string, fromByte = 0): TapeEntry[] {
  if (!Number.isSafeInteger(fromByte) || fromByte < 0) throw new Error("--from-byte requires a nonnegative integer");
  const bytes = readFileSync(resolve(inputPath));
  return harvestTapeText(bytes.subarray(fromByte).toString("utf8"));
}
export function harvestTapeFile(inputPath: string, outputPath: string, fromByte = 0): {path: string; count: number; written: boolean} {
  return writeTapeModule(readTapeFile(inputPath, fromByte), outputPath);
}
export function main(args: string[]): void {
  if (args.length !== 2 && !(args.length === 4 && args[2] === "--from-byte")) throw new Error("Usage: tsx scripts/harvest-tape.ts <log-or-tool-result.json> <Content/Tapes/Name.ts> [--from-byte N]");
  const result = harvestTapeFile(args[0], args[1], args.length === 4 ? Number(args[3]) : 0);
  process.stdout.write("Validated " + result.count + " tape records; " + (result.written ? "wrote " : "already current: ") + result.path + "\n");
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {main(process.argv.slice(2));} catch (error) {
    process.stderr.write((error instanceof Error ? error.message : "Tape harvest failed") + "\n"); process.exitCode = 1;
  }
}
