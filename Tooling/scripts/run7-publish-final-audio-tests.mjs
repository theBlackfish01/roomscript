import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const root=path.resolve(import.meta.dirname,'../..'),stage=path.join(root,'Tooling/staging'),assets=path.join(root,'Assets/Scripts');
const hash=data=>crypto.createHash('sha256').update(data).digest('hex');
const guard=JSON.parse(fs.readFileSync(path.join(stage,'run7-polish-native-start-source.json'),'utf8'));
const polish=path.join(assets,guard.name),polishBytes=fs.readFileSync(polish);
if(hash(polishBytes)!==guard.sha256)throw Error('Polish source changed; publication refused');
const scenario='RoomscriptGeneratedVoiceLeafScenario.ts',destination=path.join(assets,scenario);
if(fs.existsSync(destination))throw Error('Generated voice scenario already exists; inspect before overwrite');
const indexPath=path.join(assets,'RoomscriptLeafIndex.ts'),index=fs.readFileSync(indexPath,'utf8');
if(index.includes('roomscript-generated-voices'))throw Error('Scenario already registered');
const marker='  static scenariosIndex: ScenarioMetadata[] = [';
if(!index.includes(marker))throw Error('Registry insertion marker missing');
const updated='import {RoomscriptGeneratedVoiceLeafScenario} from "./RoomscriptGeneratedVoiceLeafScenario";\n'+index.replace(marker,marker+'\n    {id:"roomscript-generated-voices",typename:RoomscriptGeneratedVoiceLeafScenario.getTypeName(),parameters:{seed:"7",source:"file"}},');
const oldIds=[...index.matchAll(/id\s*:\s*"([^"]+)"/g)].map(m=>m[1]);
for(const id of oldIds)if(!updated.includes('"'+id+'"'))throw Error('Lost registry entry '+id);
if(fs.readFileSync(indexPath,'utf8')!==index)throw Error('Registry changed during preparation');
fs.copyFileSync(path.join(stage,guard.name),polish);
fs.copyFileSync(path.join(stage,scenario),destination);
fs.writeFileSync(indexPath,updated);
const paths=[guard.name,scenario,'RoomscriptLeafIndex.ts'].map(name=>({path:'Assets/Scripts/'+name,sha256:hash(fs.readFileSync(path.join(assets,name)))}));
const result={at:new Date().toISOString(),paths,previousRegistryEntries:oldIds.length,registryEntries:oldIds.length+1,verification:'Source hash guard and exact byte publication; runtime compile and LEAF still required.'};
fs.writeFileSync(path.join(stage,'run7-final-audio-tests-publication.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
